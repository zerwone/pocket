import { fileURLToPath } from 'node:url';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { parse as parseToml } from 'smol-toml';
import { Args, Ctx } from '../ctx.js';
import { DEFAULT_PORT, localToken, Paths, paths, PocketError, readJson, readText, writePrivate } from '../config.js';

export interface Attachments {
  claude?: { agent: string; launcher: string; vscode?: { file: string; existed: boolean; before: string; after: string } };
  codex?: { agent: string; file: string; existed: boolean; backup: string; after: string; origModelProviderLine: string | null; launcher: string };
  cursor?: { agent: string; printed: string };
}

export function readAttachments(p: Paths): Attachments {
  return readJson<Attachments>(p.attachments, {});
}

function saveAttachments(p: Paths, a: Attachments) {
  writePrivate(p.attachments, JSON.stringify(a, null, 2) + '\n');
}

function port(ctx: Ctx, args: Args): number {
  return Number(args.flags.port ?? ctx.env.POCKET_PORT ?? DEFAULT_PORT);
}

function binDir(ctx: Ctx, args: Args, p: Paths): string {
  return typeof args.flags['bin-dir'] === 'string' ? path.resolve(ctx.cwd, args.flags['bin-dir']) : p.bin;
}

const isWin = () => process.platform === 'win32';

const POCKET_MAIN = () => fileURLToPath(new URL('../main.js', import.meta.url));

function writeLauncher(dir: string, name: string, vars: Record<string, string>, unset: string[], exe: string, prt: number): string {
  fs.mkdirSync(dir, { recursive: true });
  const node = process.execPath;
  if (isWin()) {
    const file = path.join(dir, `${name}.cmd`);
    const lines = ['@echo off', `rem generated by pocket; remove with: pocket detach`, ...unset.map((u) => `set "${u}="`), ...Object.entries(vars).map(([k, v]) => `set "${k}=${v}"`), `"${node}" "${POCKET_MAIN()}" daemon start --port ${prt} >nul 2>&1`, `${exe} %*`];
    fs.writeFileSync(file, lines.join('\r\n') + '\r\n', { mode: 0o700 });
    return file;
  }
  const q = (v: string) => `'${v.replace(/'/g, `'\\''`)}'`;
  const file = path.join(dir, name);
  const lines = ['#!/bin/sh', '# generated by pocket; remove with: pocket detach', ...unset.map((u) => `unset ${u}`), ...Object.entries(vars).map(([k, v]) => `export ${k}=${q(v)}`), `${q(node)} ${q(POCKET_MAIN())} daemon start --port ${prt} >/dev/null 2>&1`, `exec ${exe} "$@"`];
  fs.writeFileSync(file, lines.join('\n') + '\n', { mode: 0o700 });
  fs.chmodSync(file, 0o700);
  return file;
}

// ------------------------------------------------------------------ VS Code

export function vscodeSettingsPath(env: NodeJS.ProcessEnv): string {
  if (process.platform === 'win32') return path.join(env.APPDATA ?? path.join(os.homedir(), 'AppData', 'Roaming'), 'Code', 'User', 'settings.json');
  if (process.platform === 'darwin') return path.join(os.homedir(), 'Library', 'Application Support', 'Code', 'User', 'settings.json');
  return path.join(env.XDG_CONFIG_HOME ?? path.join(os.homedir(), '.config'), 'Code', 'User', 'settings.json');
}

const VS_KEY = 'claudeCode.environmentVariables';

function vscodeAdd(text: string | null, vars: Record<string, string>): string {
  const obj = text && text.trim() ? JSON.parse(text) : {};
  const list: { name: string; value: string }[] = Array.isArray(obj[VS_KEY]) ? obj[VS_KEY].filter((e: any) => !(e?.name in vars)) : [];
  for (const [name, value] of Object.entries(vars)) list.push({ name, value });
  obj[VS_KEY] = list;
  return JSON.stringify(obj, null, 4) + '\n';
}

// ------------------------------------------------------------------ Codex config.toml (text edit, never re-serialised)

export const CODEX_BEGIN = '# >>> pocket: added by `pocket attach codex`; remove with `pocket detach codex`';
export const CODEX_END = '# <<< pocket';
const MP_LINE_RE = /^[ \t]*model_provider[ \t]*=/;

function eolOf(text: string) {
  return text.includes('\r\n') ? '\r\n' : '\n';
}

function stripOurs(o: any) {
  const c = structuredClone(o ?? {});
  for (const t of ['model_providers', 'profiles']) {
    if (c[t]) {
      delete c[t].pocket;
      if (!Object.keys(c[t]).length) delete c[t];
    }
  }
  return c;
}

/** Pure: the attached config text. pocket only adds its own provider and a `pocket` profile, so plain
 *  `codex` keeps working exactly as before; `codex-pocket` runs `codex --profile pocket`.
 *  origLine is kept in the return shape for detach of configs attached by pocket <= 0.1.1. */
export function codexAttachText(orig: string | null, baseUrl: string, agent: string): { text: string; origLine: string | null } {
  const src = orig ?? '';
  let before: any = {};
  try {
    before = parseToml(src);
  } catch (e: any) {
    throw new PocketError(`~/.codex/config.toml does not parse as TOML (${e.message}); not touching it`);
  }
  if (before.model_providers?.pocket) throw new PocketError('config.toml already defines [model_providers.pocket]; remove it or run `pocket detach codex` first');
  if (before.profiles?.pocket) throw new PocketError('config.toml already defines [profiles.pocket]; remove it or run `pocket detach codex` first');
  const eol = eolOf(src);
  let body = src;
  if (body.length && !body.endsWith(eol)) body += eol;
  const block = [
    CODEX_BEGIN,
    '[model_providers.pocket]',
    'name = "pocket"',
    `base_url = "${baseUrl}"`,
    'env_key = "POCKET_TOKEN"',
    'wire_api = "responses"',
    `http_headers = { "x-pocket-agent" = "${agent}" }`,
    '',
    '[profiles.pocket]',
    'model_provider = "pocket"',
    CODEX_END,
  ].join(eol);
  const text = body + (body.trim().length ? eol : '') + block + eol;
  let after: any;
  try {
    after = parseToml(text);
  } catch (e: any) {
    throw new PocketError(`adding the pocket provider would break config.toml (${e.message}); not touching it`);
  }
  if (JSON.stringify(stripOurs(after)) !== JSON.stringify(stripOurs(before))) throw new PocketError('internal: attach would change other keys in config.toml; refusing');
  if (after.model_providers?.pocket?.base_url !== baseUrl || after.profiles?.pocket?.model_provider !== 'pocket') throw new PocketError('internal: attach did not produce the pocket provider; refusing');
  return { text, origLine: null };
}

/** Pure: undo our edit when the file changed after attach (so the backup cannot be restored as is). */
export function codexDetachText(cur: string, origLine: string | null): string {
  const eol = eolOf(cur);
  const lines = cur.split(/\r?\n/);
  const b = lines.indexOf(CODEX_BEGIN);
  const e = lines.indexOf(CODEX_END);
  if (b >= 0 && e > b) {
    lines.splice(b, e - b + 1);
    if (b > 0 && lines[b - 1] === '' && (lines[b] === undefined || lines[b] === '')) lines.splice(b - 1, 1);
  }
  const i = lines.findIndex((l) => l.startsWith('model_provider = "pocket" # pocket'));
  if (i >= 0) {
    if (origLine !== null) lines[i] = origLine;
    else lines.splice(i, 1);
  }
  return lines.join(eol);
}

export function codexConfigPath(env: NodeJS.ProcessEnv): string {
  return path.join(env.CODEX_HOME ?? path.join(os.homedir(), '.codex'), 'config.toml');
}

// ------------------------------------------------------------------ commands

export async function cmdAttach(ctx: Ctx, args: Args): Promise<number> {
  const target = args._[0];
  const p = paths(ctx.env);
  const token = localToken(p);
  const prt = port(ctx, args);
  const att = readAttachments(p);

  if (target === 'claude') {
    const agent = typeof args.flags.as === 'string' ? args.flags.as : 'claude-code';
    const vars = {
      ANTHROPIC_BASE_URL: `http://127.0.0.1:${prt}/anthropic`,
      ANTHROPIC_AUTH_TOKEN: token,
      ANTHROPIC_CUSTOM_HEADERS: `x-pocket-agent: ${agent}`,
    };
    const launcher = writeLauncher(binDir(ctx, args, p), 'claude-pocket', vars, ['ANTHROPIC_API_KEY'], 'claude', prt);
    const rec: Attachments['claude'] = { agent, launcher };
    ctx.out(`wrote ${launcher}`);
    const vsFile = typeof args.flags['vscode-settings'] === 'string' ? args.flags['vscode-settings'] : vscodeSettingsPath(ctx.env);
    if (args.flags.vscode) {
      const before = readText(vsFile);
      let after: string;
      try {
        after = vscodeAdd(before, vars);
      } catch {
        ctx.err(`${vsFile} has comments or is not plain JSON; not editing it. Add this to "${VS_KEY}" yourself:\n${JSON.stringify(Object.entries(vars).map(([name, value]) => ({ name, value })), null, 2)}`);
        after = '';
      }
      if (after) {
        fs.mkdirSync(path.dirname(vsFile), { recursive: true });
        fs.writeFileSync(vsFile, after);
        rec.vscode = { file: vsFile, existed: before !== null, before: before ?? '', after };
        ctx.out(`added ${Object.keys(vars).join(', ')} to ${VS_KEY} in ${vsFile}`);
      }
    } else {
      ctx.out(`VS Code: rerun with --vscode to add the same variables to "${VS_KEY}" in ${vsFile}`);
    }
    att.claude = rec;
    saveAttachments(p, att);
    ctx.out(`Run Claude Code through pocket with: ${launcher}   (put ${path.dirname(launcher)} on your PATH to type claude-pocket)`);
    return 0;
  }

  if (target === 'codex') {
    if (att.codex) {
      ctx.out(`codex is already attached (${att.codex.file})`);
      return 0;
    }
    const agent = typeof args.flags.as === 'string' ? args.flags.as : 'codex';
    const file = typeof args.flags.config === 'string' ? path.resolve(ctx.cwd, args.flags.config) : codexConfigPath(ctx.env);
    const origBuf = fs.existsSync(file) ? fs.readFileSync(file) : null;
    const orig = origBuf ? origBuf.toString('utf8') : null;
    if (origBuf && Buffer.from(orig!, 'utf8').compare(origBuf) !== 0) throw new PocketError(`${file} is not UTF-8; not touching it`);
    const { text, origLine } = codexAttachText(orig, `http://127.0.0.1:${prt}/openai/v1`, agent);
    const backup = file + '.pocket-backup';
    if (origBuf) fs.writeFileSync(backup, origBuf, { mode: fs.statSync(file).mode & 0o777 });
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
    const launcher = writeLauncher(binDir(ctx, args, p), 'codex-pocket', { POCKET_TOKEN: token }, [], 'codex --profile pocket', prt);
    att.codex = { agent, file, existed: !!origBuf, backup, after: text, origModelProviderLine: origLine, launcher };
    saveAttachments(p, att);
    ctx.out(`added [model_providers.pocket] and [profiles.pocket] to ${file}${origBuf ? ` (backup: ${backup})` : ''}; plain \`codex\` is unchanged`);
    ctx.out(`Codex reads the local token from POCKET_TOKEN. Run: ${launcher}   (or export POCKET_TOKEN yourself)`);
    return 0;
  }

  if (target === 'cursor') {
    const agent = typeof args.flags.as === 'string' ? args.flags.as : 'cursor';
    const base = `http://127.0.0.1:${prt}/a/${agent}/openai/v1`;
    const text = [
      'Cursor → Settings → Models → OpenAI API Key:',
      `  Override OpenAI Base URL:  ${base}`,
      `  OpenAI API Key:            ${token}`,
      '  Then add a model name pocket maps by tier, e.g. gpt-4.1 (strong) or gpt-4.1-mini (fast).',
      '',
      'Notes:',
      '  - Only chat requests that use your own OpenAI key go through this URL. Agent/Composer and',
      "    Cursor's own models may not route through pocket at all.",
      '  - Cursor may send custom-model requests from its servers rather than your machine; a 127.0.0.1',
      '    URL is then unreachable. pocket will not expose itself to the network to make that work.',
    ].join('\n');
    ctx.out(text);
    if (args.flags.write) {
      ctx.err(
        'pocket attach cursor --write: not done. Cursor keeps the OpenAI key and base URL in its internal app database, not in a settings file pocket can edit safely and show as a diff. Paste the values above instead.',
      );
      return 2;
    }
    att.cursor = { agent, printed: base };
    saveAttachments(p, att);
    return 0;
  }

  throw new PocketError('usage: pocket attach claude|codex|cursor [--as <agent>] [--port 3460] [--bin-dir dir] [--vscode]');
}

export async function cmdDetach(ctx: Ctx, args: Args): Promise<number> {
  const target = args._[0];
  const p = paths(ctx.env);
  const att = readAttachments(p);

  if (target === 'claude') {
    const rec = att.claude;
    if (!rec) {
      ctx.out('claude is not attached');
      return 0;
    }
    fs.rmSync(rec.launcher, { force: true });
    ctx.out(`removed ${rec.launcher}`);
    if (rec.vscode) {
      const cur = readText(rec.vscode.file);
      if (cur === rec.vscode.after) {
        if (rec.vscode.existed) fs.writeFileSync(rec.vscode.file, rec.vscode.before);
        else fs.rmSync(rec.vscode.file, { force: true });
        ctx.out(`restored ${rec.vscode.file}`);
      } else if (cur !== null) {
        try {
          const obj = JSON.parse(cur);
          if (Array.isArray(obj[VS_KEY])) {
            obj[VS_KEY] = obj[VS_KEY].filter((e: any) => !['ANTHROPIC_BASE_URL', 'ANTHROPIC_AUTH_TOKEN', 'ANTHROPIC_CUSTOM_HEADERS'].includes(e?.name));
            fs.writeFileSync(rec.vscode.file, JSON.stringify(obj, null, 4) + '\n');
            ctx.out(`removed pocket variables from ${rec.vscode.file} (it changed since attach, so it was edited, not restored)`);
          }
        } catch {
          ctx.err(`${rec.vscode.file} changed and is not plain JSON; remove the ANTHROPIC_* entries from "${VS_KEY}" yourself`);
        }
      }
    }
    delete att.claude;
    saveAttachments(p, att);
    return 0;
  }

  if (target === 'codex') {
    const rec = att.codex;
    if (!rec) {
      ctx.out('codex is not attached');
      return 0;
    }
    const cur = readText(rec.file);
    if (cur === rec.after) {
      if (rec.existed) {
        fs.copyFileSync(rec.backup, rec.file);
        fs.rmSync(rec.backup, { force: true });
        ctx.out(`restored ${rec.file} from ${rec.backup}`);
      } else {
        fs.rmSync(rec.file, { force: true });
        ctx.out(`removed ${rec.file} (it did not exist before attach)`);
      }
    } else if (cur !== null) {
      fs.writeFileSync(rec.file, codexDetachText(cur, rec.origModelProviderLine));
      ctx.out(`${rec.file} changed after attach: removed only the pocket lines; backup kept at ${rec.backup}`);
    }
    fs.rmSync(rec.launcher, { force: true });
    delete att.codex;
    saveAttachments(p, att);
    return 0;
  }

  if (target === 'cursor') {
    delete att.cursor;
    saveAttachments(p, att);
    ctx.out('cursor: remove the base URL and key from Cursor → Settings → Models yourself (pocket never wrote them)');
    return 0;
  }

  throw new PocketError('usage: pocket detach claude|codex|cursor');
}
